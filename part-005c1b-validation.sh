##########################################################
# VALIDASI FILE
##########################################################

echo ""
echo "Checking files..."

FILES=(
"src/styles/utilities.css"
"src/main.tsx"
)

ERROR=0

for FILE in "${FILES[@]}"
do
    if [ -f "$FILE" ]; then
        echo "✓ $FILE"
    else
        echo "✗ $FILE"
        ERROR=1
    fi
done

if [ "$ERROR" -eq 1 ]; then
    echo ""
    echo "Validation Failed."
    exit 1
fi

